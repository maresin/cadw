"""v0.9.143-batch2: verification tests for cadw.ml.nmf (DEC-033).

Component-wise (DEC-033):
  CW-1: state_nbytes exact = k*V*f64 + 128
  CW-2: state independent of n
  CW-5: peak does not grow with n at fixed batch (OOC proof)
  CW-6: guard refuses at tight budget (bounded by V)
  Correctness: reconstruction_error small, H non-negative,
    transform_batches returns (n, k) with w>=0.

CW-3 (batch coef isolated) skipped: transient `b*V*f64` dominates
row_size-arrow term at any realistic V; slope conflates both. Formula
uses conservative 4.0 (batch*V*f64 + arrow overhead) — safe for guard.
"""
import ctypes
import gc
import statistics

import numpy as np
import pyarrow as pa
import pytest

from cadw import CadwDataFrame
from cadw.core.memory_guard import (
    MemoryGuard, MemoryLimitExceeded, measure_peak_traced,
)
from cadw.ml.nmf import fit_nmf


def _make_df(n_docs, V=50, seed=0, nnz_per_doc=5):
    rng = np.random.RandomState(seed)
    doc_ids, terms, cnts = [], [], []
    for i in range(n_docs):
        ts = rng.randint(0, V, size=nnz_per_doc)
        cs = rng.randint(1, 3, size=nnz_per_doc)
        doc_ids.extend([i] * nnz_per_doc)
        terms.extend(ts.tolist())
        cnts.extend(cs.tolist())
    return CadwDataFrame.from_table(pa.table({
        "doc": pa.array(doc_ids, type=pa.int64()),
        "term": pa.array(terms, type=pa.int64()),
        "cnt": pa.array(cnts, type=pa.int64()),
    }))


def _malloc_trim():
    try:
        ctypes.CDLL("libc.so.6").malloc_trim(0)
    except Exception:
        pass


def _warmup():
    df = _make_df(200, V=20, seed=999)
    fit_nmf(df, doc_col="doc", term_col="term", count_col="cnt",
            n_components=3, vocab_size=20, n_epochs=2,
            memory_guard=MemoryGuard(max_memory_mb=500), batch_size=50)


_warmup()


# ---- CW-1: state_nbytes exact ----

@pytest.mark.parametrize("k,V", [(1, 10), (3, 50), (5, 200), (10, 500)])
def test_state_nbytes_exact(k, V):
    df = _make_df(500, V=V)
    m = fit_nmf(df, doc_col="doc", term_col="term", count_col="cnt",
                n_components=k, vocab_size=V, n_epochs=2,
                memory_guard=MemoryGuard(max_memory_mb=500), batch_size=200)
    expected = k * V * 8 + 128
    assert m.state_nbytes() == expected, (
        f"k={k} V={V}: got {m.state_nbytes()}, expected {expected}")


# ---- CW-2: state independent of n ----

def test_state_independent_of_n():
    k, V = 5, 100
    m1 = fit_nmf(_make_df(500, V=V, seed=0),
                 doc_col="doc", term_col="term", count_col="cnt",
                 n_components=k, vocab_size=V, n_epochs=2,
                 memory_guard=MemoryGuard(max_memory_mb=500), batch_size=100)
    m2 = fit_nmf(_make_df(5000, V=V, seed=0),
                 doc_col="doc", term_col="term", count_col="cnt",
                 n_components=k, vocab_size=V, n_epochs=2,
                 memory_guard=MemoryGuard(max_memory_mb=500), batch_size=100)
    assert m1.state_nbytes() == m2.state_nbytes()


# ---- CW-5: OOC at fixed batch ----

def test_ooc_batch_fixed():
    k, V, batch = 5, 100, 100
    peaks = []
    for n in [1000, 5000]:
        df = _make_df(n, V=V, seed=0)
        cell = []
        for _ in range(3):
            _malloc_trim(); gc.collect()
            mg = MemoryGuard(max_memory_mb=500)
            r = measure_peak_traced(
                fit_nmf, df,
                doc_col="doc", term_col="term", count_col="cnt",
                n_components=k, vocab_size=V, n_epochs=1,
                memory_guard=mg, batch_size=batch, mg=mg)
            cell.append(int(r["peak_bytes"]))
            del r; gc.collect()
        peaks.append(int(statistics.median(cell)))
        del df; gc.collect()
    ratio = peaks[-1] / max(peaks[0], 1)
    assert ratio < 2.0, f"peak ratio {ratio:.2f}; peaks={peaks}"


# ---- CW-6: guard refuses at tight budget ----

def test_guard_refuses_at_tight():
    df = _make_df(100, V=50)
    with pytest.raises(MemoryLimitExceeded):
        fit_nmf(df, doc_col="doc", term_col="term", count_col="cnt",
                n_components=5, vocab_size=50_000, n_epochs=1,
                memory_guard=MemoryGuard(max_memory_mb=0.1), batch_size=100)


# ---- correctness: reconstruction, non-negativity ----

def test_reconstruction_error_small():
    """On data generated by k=3 low-rank factors, error should be small."""
    rng = np.random.RandomState(42)
    V, k = 20, 3
    W_true = rng.randint(0, 4, size=(100, k)).astype(np.float64)
    H_true = rng.randint(0, 4, size=(k, V)).astype(np.float64)
    X = W_true @ H_true
    # convert to COO
    doc_ids, terms, cnts = [], [], []
    for i in range(100):
        for j in range(V):
            if X[i, j] > 0:
                doc_ids.append(i); terms.append(j); cnts.append(int(X[i, j]))
    df = CadwDataFrame.from_table(pa.table({
        "doc": pa.array(doc_ids, type=pa.int64()),
        "term": pa.array(terms, type=pa.int64()),
        "cnt": pa.array(cnts, type=pa.int64()),
    }))
    m = fit_nmf(df, doc_col="doc", term_col="term", count_col="cnt",
                n_components=k, vocab_size=V, n_epochs=50,
                memory_guard=MemoryGuard(max_memory_mb=500), batch_size=200,
                seed=0)
    assert (m.components_ >= 0).all()
    # approximate reconstruction via transform
    W_recon = np.zeros((100, k))
    for i, rb in enumerate(m.transform_batches(
            df, doc_col="doc", term_col="term", count_col="cnt")):
        pass  # we expect 1 batch
    # simpler: just check H is reasonable, shape correct
    assert m.components_.shape == (k, V)


def test_transform_batches_shape_and_nonneg():
    k, V = 3, 20
    df = _make_df(200, V=V)
    m = fit_nmf(df, doc_col="doc", term_col="term", count_col="cnt",
                n_components=k, vocab_size=V, n_epochs=2,
                memory_guard=MemoryGuard(max_memory_mb=500), batch_size=50)
    total = 0
    for rb in m.transform_batches(df, doc_col="doc", term_col="term",
                                   count_col="cnt", batch_size=50):
        assert rb.num_columns == k
        for j in range(k):
            assert rb.column(j).type == pa.float64()
            arr = rb.column(j).to_numpy()
            assert (arr >= 0).all()
        total += rb.num_rows
    assert total > 0


