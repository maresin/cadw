#!/usr/bin/env python3
"""Render docs/ml_tools/MATRIX.md + docs/tasks/<section><subtype>.md.

Deterministic: same YAML in -> identical Markdown out. test_render_matrix.py
regenerates into tmp and asserts byte-equality with disk.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from docs.ml_tools.benchmarks_loader import load_benchmarks  # noqa: E402
from docs.ml_tools.schema import load_section  # noqa: E402

ML_TOOLS = ROOT / "docs/ml_tools"
TASKS = ROOT / "docs/tasks"
MATRIX = ML_TOOLS / "MATRIX.md"

_IMPL_LEGEND = {
    "verified_in_cadw": "✓ cadw",
    "verified_by_agent": "✓ agent",
    "described_only": "desc",
    "not_implemented_in_cadw": "export",
}


def _impl_summary(card) -> str:
    flags = []
    s = card.implementation_status
    if s.verified_in_cadw:
        flags.append(_IMPL_LEGEND["verified_in_cadw"])
    if s.verified_by_agent:
        flags.append(_IMPL_LEGEND["verified_by_agent"])
    if s.described_only:
        flags.append(_IMPL_LEGEND["described_only"])
    if s.not_implemented_in_cadw:
        flags.append(_IMPL_LEGEND["not_implemented_in_cadw"])
    return ", ".join(flags) if flags else "—"


def _load_all_sections():
    return [
        load_section(p)
        for p in sorted(ML_TOOLS.glob("[A-Z]_*.yaml"))
    ]


def render_matrix_md(sections) -> str:
    lines = [
        "# ML tools matrix (auto-generated by scripts/render_matrix.py)",
        "",
        "Do not edit this file. Edit the section YAMLs under `docs/ml_tools/`",
        "and re-run `python scripts/render_matrix.py`.",
        "",
        "Legend: **✓ cadw** = verified_in_cadw, **✓ agent** = verified_by_agent,",
        "**desc** = described_only, **export** = tier3_export (via to_batches).",
        "",
        "| Section | Subtype | Model | Tier | Level | Roles | Status | Anchor |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for sec in sections:
        for st in sec.subtypes:
            anchor = next(
                (m.name for m in st.metrics if m.combination == "anchor"),
                "—",
            )
            for m in st.models:
                lines.append(
                    f"| {sec.section} | {st.id} {st.name} | {m.name} "
                    f"| {m.tier} | {m.tier_level} | "
                    f"{', '.join(m.roles)} | {_impl_summary(m)} | {anchor} |"
                )
    return "\n".join(lines) + "\n"


def render_subtype_md(sec, st) -> str:
    lines = [
        f"# {st.id} — {st.name}",
        "",
        f"*Section:* {sec.section} — {sec.name}",
        "",
        f"**Description:** {st.description}",
        "",
    ]
    if st.real_life:
        lines.append("**Real-life examples:**")
        lines.extend(f"- {x}" for x in st.real_life)
        lines.append("")

    if st.benchmarks:
        lines.append("## Benchmarks")
        for b in st.benchmarks:
            lines.append(f"- **{b.name}** — {b.url}")
            if b.metrics:
                lines.append(f"  - metrics: {', '.join(b.metrics)}")
        lines.append("")

    lines.append("## Models")
    for m in st.models:
        lines.append(f"### {m.name} — {m.tier} / {m.tier_level}")
        lines.append("")
        lines.append(f"**Roles:** {', '.join(m.roles)}")
        lines.append(f"**Status:** {_impl_summary(m)}")
        lines.append("")
        lines.append(f"**Purpose:** {m.purpose}")
        if m.real_life_examples:
            lines.append("")
            lines.append("**Use cases:**")
            lines.extend(f"- {x}" for x in m.real_life_examples)
        if m.config:
            lines.append("")
            lines.append(f"**Config:** `{m.config}`")
        if m.cadw_module:
            lines.append("")
            lines.append(f"**CADW:** `{m.cadw_module}.{m.cadw_function}`")
        lines.append("")
        if not m.benchmark_results:
            lines.append("**Benchmarks:** —")
            lines.append("")
        else:
            lines.append("**Benchmarks:**")
            for br in m.benchmark_results:
                val = "null" if br.value is None else f"{br.value}"
                std = f" ± {br.std}" if br.std is not None else ""
                n = f" (n={br.n_datasets})" if br.n_datasets else ""
                lines.append(
                    f"- **[{br.attribution}]** {br.benchmark} → "
                    f"{br.metric}={val}{std}{n}"
                )
                lines.append(f"  - algorithm: `{br.algorithm}` "
                             f"({br.algorithm_source_kind})")
                if br.reproduces:
                    lines.append(f"  - reproduces: `{br.reproduces}`")
                lines.append(f"  - number: {br.benchmark_url}")
                if br.algorithm_source_url:
                    lines.append(f"  - code/paper: {br.algorithm_source_url}")
                if br.note:
                    lines.append(f"  - note: {br.note}")
            lines.append("")

    if st.metrics:
        lines.append("## Metrics")
        for mc in st.metrics:
            lines.append(
                f"- **{mc.name}** ({mc.combination}, {mc.direction})"
            )
            lines.append(f"  - {mc.responsibility}")
            if mc.special:
                lines.append(f"  - *special:* {mc.special}")
        lines.append("")

    if st.ensemble_recommendation:
        lines.append("## Ensemble rules")
        for rule in st.ensemble_recommendation:
            models = " + ".join(rule.models)
            roles = ", ".join(rule.roles)
            lines.append(
                f"- **[{roles}]** → {models} (max_per_role={rule.max_per_role})"
            )
            if rule.note:
                lines.append(f"  - {rule.note}")
    return "\n".join(lines).rstrip() + "\n"


def main():
    sections = _load_all_sections()
    bm = load_benchmarks(ML_TOOLS / "benchmarks.yaml")

    matrix_text = render_matrix_md(sections)
    MATRIX.write_text(matrix_text)
    print(f"wrote {MATRIX.relative_to(ROOT)} "
          f"({len(matrix_text.splitlines())} lines)")

    TASKS.mkdir(parents=True, exist_ok=True)
    n = 0
    for sec in sections:
        for st in sec.subtypes:
            fname = f"{sec.section}{st.id.replace('.', '_')}.md"
            text = render_subtype_md(sec, st)
            (TASKS / fname).write_text(text)
            n += 1
    print(f"wrote {n} files under {TASKS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()